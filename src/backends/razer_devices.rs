//! Known Razer USB HID backlight descriptors ported from OpenRGB RazerDevices/RazerControllerDetect.

use crate::device::DeviceKind;

/// Razer LED matrix protocol family.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RazerMatrixType {
    /// Legacy single-zone or non-matrix device.
    None,
    /// Standard Chroma matrix protocol (`0x03`).
    Standard,
    /// Extended Chroma matrix protocol (`0x0F`).
    Extended,
    /// Linear LED strip/zone protocol.
    Linear,
    /// Extended ARGB controller protocol.
    ExtendedArgb,
    /// Device-specific custom protocol variant.
    Custom,
}

/// Static descriptor for a known Razer HID peripheral interface.
#[derive(Debug, Clone, Copy)]
pub struct RazerDeviceSpec {
    /// Human-readable product name.
    pub name: &'static str,
    /// USB Product ID.
    pub pid: u16,
    /// Peripheral form factor.
    pub kind: DeviceKind,
    /// LED matrix protocol variant.
    pub matrix: RazerMatrixType,
    /// Default Razer HID transaction ID.
    pub tx_id: u8,
    /// Default LED region ID.
    pub led_id: u8,
    /// Optional USB interface number filter.
    pub interface: Option<i32>,
    /// Optional HID usage page filter.
    pub usage_page: Option<u16>,
    /// Optional HID usage ID filter.
    pub usage: Option<u16>,
}

